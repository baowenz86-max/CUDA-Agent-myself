// Launcher for relu_forward: handles arbitrary strides by using shape and strides arrays.
// The kernel will iterate over all elements, compute coordinates, and access with strides.
// This is general but may be slower than specialized contiguous, but acceptable for correctness.
// We can also provide a fast path in the launcher if strides indicate contiguous, but we can keep simple.

extern "C" void relu_forward_launcher(
    float* y,
    const float* x,
    int64_t numel,
    int ndim,
    const int64_t* shape,
    const int64_t* x_strides,
    const int64_t* y_strides,
    cudaStream_t stream)
{
    if (numel == 0) return;
    const int block_size = 256;
    int grid_size = (int)((numel + block_size - 1) / block_size);
    if (grid_size > 65535) {
        grid_size = 65535;
    }
    relu_forward_kernel<<<grid_size, block_size, 0, stream>>>(
        y, x, numel, ndim, shape, x_strides, y_strides);
}

__global__ void relu_forward_kernel(
    float* __restrict__ y,
    const float* __restrict__ x,
    int64_t numel,
    int ndim,
    const int64_t* __restrict__ shape,
    const int64_t* __restrict__ x_strides,
    const int64_t* __restrict__ y_strides)
{
    int64_t idx = blockIdx.x * blockDim.x + threadIdx.x;
    int64_t stride = blockDim.x * gridDim.x;
    for (int64_t linear = idx; linear < numel; linear += stride) {
        // Compute coordinates
        int64_t remaining = linear;
        int64_t x_index = 0;
        int64_t y_index = 0;
        for (int d = ndim - 1; d >= 0; --d) {
            int64_t coord = remaining % shape[d];
            remaining /= shape[d];
            x_index += coord * x_strides[d];
            y_index += coord * y_strides[d];
        }
        y[y_index] = fmaxf(x[x_index], 0.0f);
    }
}

